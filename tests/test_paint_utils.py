class PaintUtilsTestCase(unittest.TestCase):
    def setUp(self):
        self.app = create_app('testing')
        self.app_context = self.app.app_context()
        self.app_context.push()

    def tearDown(self):
        db.session.remove()
        db.drop_all()
        self.app_context.pop()


    def test_figure2ndarray(self):
        r = np.array([x, y]).T
        ndarray = utils.figure2ndarray(r)
        self.assertEqual(ndarray.shape, (30, 30))

    def test_get_figure_tag(self):
        with self.app_context, self.app.test_request_context():
            figure_tag = utils.get_figure_tag(x, y)
        self.assertTrue('<g class="deletable">' in figure_tag)

    def test_scale_coordinates(self):
        x = np.array([0, 50, 100])
        y = np.array([200, 210, 220])
        x_scaled, y_scaled, _, _, _ = utils.scale_coordinates(x, y)
        self.assertTrue(np.allclose(x_scaled, np.array([ 2.5, 15. , 27.5])))
        self.assertTrue(np.allclose(y_scaled, np.array([12.5, 15. , 17.5])))

    def test_scale_back_coordinates(self):
        x_scaled = np.array([ 2.5, 15. , 27.5])
        y_scaled = np.array([12.5, 15. , 17.5])
        scale = 4
        x_scaled_med = 12.5
        y_scaled_med = 52.5
        x, y = utils.scale_back_coordinates(
            x_scaled, y_scaled, scale, x_scaled_med, y_scaled_med
        )
        self.assertTrue(np.allclose(x, np.array([0, 50, 100])))
        self.assertTrue(np.allclose(y, np.array([200, 210, 220])))
